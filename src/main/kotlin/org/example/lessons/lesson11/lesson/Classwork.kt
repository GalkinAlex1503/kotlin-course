package org.example.org.example.lessons.lesson11.lesson
//
//Функции — это основной строительный блок программ, который позволяет объединять повторяющийся код в единые логические блоки. В этом уроке мы разберемся, как определять функции в Kotlin, какими бывают их сигнатуры, модификаторы доступа и как они работают с возвращаемыми значениями.
//
//Определение функций
//Функция в Kotlin определяется с помощью ключевого слова fun, за которым следует имя функции, параметры (если есть) и тип возвращаемого значения (если функция что-то возвращает).
//
//Синтаксис функции:
//
//fun имяФункции(параметры): ТипВозвращаемогоЗначения {
//    // Тело функции
//    return значение
//}
//Пример функции без параметров и возвращаемого значения:
//
//fun sayHello() {
//    println("Hello, world!")
//}
//Здесь sayHello — это функция, которая не принимает параметров и не возвращает значения. Она просто выводит "Hello, world!" в консоль.
//
//Пример функции с параметрами:
//
//fun greetUser(name: String) {
//    println("Hello, $name!")
//}
//Функция greetUser принимает один параметр name типа String и выводит приветственное сообщение с указанным именем.
//
//Возвращаемые значения
//Функция в Kotlin может возвращать значение. Для указания типа возвращаемого значения используется двоеточие : после круглых скобок с параметрами.
//
//Пример функции, возвращающей значение:
//
//fun sum(a: Int, b: Int): Int {
//    return a + b
//}
//Функция sum принимает два параметра типа Int и возвращает их сумму, также типа Int.
//
//Если функция ничего не возвращает, то тип возвращаемого значения — Unit. Обычно его можно опустить, как в примерах выше. Это аналогично void в других языках программирования.
//
//fun printSum(a: Int, b: Int) {
//    println("Sum of $a and $b is ${a + b}")
//}
//Здесь функция printSum ничего не возвращает, поэтому тип Unit не указывается. Unit аналогичен void в других языках программирования, что может помочь лучше понять эту концепцию тем, кто знаком с другими языками.
//
//Однострочные функции
//Kotlin позволяет определять функции одной строкой без использования фигурных скобок {} и оператора return, если функция проста.
//
//fun multiply(a: Int, b: Int): Int = a * b
//Это пример однострочной функции multiply, которая возвращает произведение двух чисел.
//
//Модификаторы доступа: public и private
//Функции в Kotlin могут иметь модификаторы доступа. В этом уроке мы разберём только два — public и private.
//
//public — функция доступна отовсюду. По умолчанию, все функции являются публичными, если явно не указано другое.
//
//private — функция доступна только внутри того файла или класса, в котором она определена.
//
//Пример:
//
//private fun calculateDiscount(price: Double): Double {
//    return price * 0.1
//}
//fun finalPrice(price: Double): Double {
//    val discount = calculateDiscount(price)
//    return price - discount
//}
//Здесь функция calculateDiscount является приватной, что означает, что она может быть вызвана только внутри того файла, где она определена. Функция finalPrice является публичной и может быть вызвана из любого места.
//
//Ключевое слово return
//Ключевое слово return используется для того, чтобы вернуть значение из функции. Как только программа встречает return, выполнение функции завершается, и значение возвращается вызывающему коду.
//
//Пример использования return:
//
//fun max(a: Int, b: Int): Int {
//    return if (a > b) a else b
//}
//Функция max возвращает большее из двух переданных чисел с помощью выражения if-else. Также return можно использовать для немедленного завершения работы функции, даже если она не возвращает значения.
//
//Пример функции с использованием return для немедленного завершения:
//
//fun findValue(numbers: List<Int>, target: Int) {
//    for (number in numbers) {
//        if (number == target) {
//            println("Value found: $number")
//            return
//        }
//    }
//    println("Value not found")
//}
//
